#!/usr/bin/env python3
"""Practice-test kit — the real unit test as data for a course's TEACHER page.

A course's teacher folder has a two-line gen_test.py:
    from teacher_gen import main; main(unit_py="../../../build/u4/unit.py", out="test.js")
`python3 gen_test.py` writes test.js (window.TEACHER_TEST = {...}) from the unit's assessment — stems, choices, answers,
key notes, work-space heights, figures (the paper's shape specs drawn as SVG), on every form the unit has (ruling 33:
Form A, Form B; an older unit has one `sections`). `python3 gen_test.py --check` (run.py runs it before every build):
  1. test.js is exactly what unit.py gives now — the page can never carry a stale test;
  2. every `check` tuple of every item re-passes under sympy, on every form (eq / val / true / many);
  3. every item has a stem, an answer and a check; a choice item's `correct` matches its `answer` letters;
  4. each form's points are the assessment's total and each section's points are the tracker's;
  5. every figure draws (a height that ends outside its polygon is refused, as in figkit)."""
import json, os, re, sys, runpy, math

LET = "ABCDEFGH"
TWO_DAY_LINE = "This assessment runs over two class periods. Stop when the period ends; you will continue from where you stopped."
FOLLOW_THROUGH = ("If an earlier part is wrong, a later part still earns its point when the right operation is applied to your own earlier "
                  "answer — but only if that work is on the page.")
TRANSFER_FLAG = "TRANSFER ITEM — not on the practice test. Same benchmark, a surface nobody rehearsed."
SHOW_WORK = "Show your work. One point for each lettered part."
HEADER = "/* GENERATED by gen_test.py (practice kit teacher_gen.py) from the unit's unit.py — do not edit; run gen_test.py. The real unit test. */\n"

# ------------------------------------------------------------------ figures: the paper's shape specs → SVG
INK, FILL = "#111", "#e9eef7"
def svg_of(spec):
    """figkit's `shapes` spec (poly / circle / seg / ra / text) as an inline SVG, y up, drawn to its own numbers."""
    if not spec or spec.get("kind") != "shapes": return None
    xs, ys = [], []
    for sh in spec["shapes"]:
        t = sh["t"]
        if t == "poly": xs += [p[0] for p in sh["pts"]]; ys += [p[1] for p in sh["pts"]]
        elif t == "circle": (cx, cy), r = sh["c"], sh["r"]; xs += [cx - r, cx + r]; ys += [cy - r, cy + r]
        elif t == "seg": xs += [sh["a"][0], sh["b"][0]]; ys += [sh["a"][1], sh["b"][1]]
        elif t == "text": xs.append(sh["xy"][0]); ys.append(sh["xy"][1])
    if not xs: return None
    x0, x1, y0, y1 = min(xs), max(xs), min(ys), max(ys)
    span = max(x1 - x0, 1e-9); W = float(spec.get("in", 2.2)) * 96 * 1.15      # px; the paper's width in inches, a little larger on screen
    k = W / span; pt = float(spec.get("pt", 9.5)); fpx = pt * 96 / 72
    H = (y1 - y0) * k
    px = lambda p: (round((p[0] - x0) * k, 1), round((y1 - p[1]) * k, 1))
    bx = [0, W, 0, H]                                                      # the drawing's box, grown by every label's own box
    def grow(x, y, w, h): bx[0] = min(bx[0], x); bx[1] = max(bx[1], x + w); bx[2] = min(bx[2], y); bx[3] = max(bx[3], y + h)
    polys = [[tuple(q) for q in o["pts"]] for o in spec["shapes"] if o["t"] == "poly"]
    out = []
    for sh in spec["shapes"]:
        t = sh["t"]
        if t == "poly":
            out.append('<polygon points="%s" fill="%s" stroke="%s" stroke-width="1.4" stroke-linejoin="round"/>' % (" ".join("%s,%s" % px(p) for p in sh["pts"]), sh.get("fill", FILL), INK))
        elif t == "circle":
            (cx, cy), r = sh["c"], sh["r"]; c = px((cx, cy))
            if sh.get("a"):
                a0, a1 = [math.radians(a) for a in sh["a"]]
                p0 = (c[0] + r * k * math.cos(a0), c[1] - r * k * math.sin(a0)); p1 = (c[0] + r * k * math.cos(a1), c[1] - r * k * math.sin(a1))
                large = 1 if (a1 - a0) % 360 > 180 else 0
                out.append('<path d="M%.1f %.1f L%.1f %.1f A%.1f %.1f 0 %d 0 %.1f %.1f Z" fill="%s" stroke="%s" stroke-width="1.4"/>' % (c[0], c[1], p0[0], p0[1], r * k, r * k, large, p1[0], p1[1], sh.get("fill", FILL), INK))
            else:
                out.append('<circle cx="%.1f" cy="%.1f" r="%.1f" fill="%s" stroke="%s" stroke-width="1.4"/>' % (c[0], c[1], r * k, sh.get("fill", FILL), INK))
        elif t == "seg":
            a, b = px(sh["a"]), px(sh["b"])
            if sh.get("height"):
                for end in (tuple(sh["a"]), tuple(sh["b"])):
                    if not any(_in_poly(end, p) for p in polys): raise ValueError("a height ends outside its figure at %r: %r" % (end, sh))
            out.append('<line x1="%s" y1="%s" x2="%s" y2="%s" stroke="%s" stroke-width="1.2"%s/>' % (a[0], a[1], b[0], b[1], sh.get("color", INK), ' stroke-dasharray="5 4"' if sh.get("dash") else ""))
        elif t == "ra":
            (x, y), (ux, uy), (vx, vy), sz = sh["xy"], sh["u"], sh["v"], sh.get("s", 0.5)
            nu = math.hypot(ux, uy) or 1; nv = math.hypot(vx, vy) or 1
            ux, uy, vx, vy = ux / nu * sz, uy / nu * sz, vx / nv * sz, vy / nv * sz
            pts = [px((x + ux, y + uy)), px((x + ux + vx, y + uy + vy)), px((x + vx, y + vy))]
            out.append('<polyline points="%s" fill="none" stroke="%s" stroke-width="1"/>' % (" ".join("%s,%s" % p for p in pts), INK))
        elif t == "text":
            f = float(sh.get("fs", spec.get("fs", 22))) / float(spec.get("fs", 22)) * fpx
            c = list(px(sh["xy"]))
            if sh.get("off"): c[0] += sh["off"][0] * f; c[1] -= sh["off"][1] * f
            ha = {"left": "start", "right": "end"}.get(sh.get("ha", "center"), "middle")
            va = {"top": "hanging", "bottom": "auto", "baseline": "auto"}.get(sh.get("va", "center"), "central")
            tw = 0.62 * f * len(str(sh["s"])); tx = c[0] - (0 if ha == "start" else tw if ha == "end" else tw / 2)
            grow(tx, c[1] - 0.6 * f, tw, 1.2 * f)
            out.append('<text x="%.1f" y="%.1f" font-size="%.1f" font-weight="600" text-anchor="%s" dominant-baseline="%s" fill="%s">%s</text>' % (c[0], c[1], f, ha, va, sh.get("color", INK), _esc(str(sh["s"]))))
    m = 6; vx, vy, w, h = bx[0] - m, bx[2] - m, bx[1] - bx[0] + 2 * m, bx[3] - bx[2] + 2 * m
    return '<svg class="tfig" xmlns="http://www.w3.org/2000/svg" viewBox="%.1f %.1f %.1f %.1f" width="%.0f" height="%.0f" role="img" aria-label="figure" style="font-family:Lexend,system-ui,sans-serif">%s</svg>' % (vx, vy, w, h, w, h, "".join(out))

def _in_poly(p, poly):
    x, y = p; inside = False; n = len(poly)
    for i in range(n):
        (x1, y1), (x2, y2) = poly[i], poly[(i + 1) % n]
        if min(x1, x2) - 1e-9 <= x <= max(x1, x2) + 1e-9 and min(y1, y2) - 1e-9 <= y <= max(y1, y2) + 1e-9 and abs((x2 - x1) * (y - y1) - (y2 - y1) * (x - x1)) < 1e-9: return True
        if (y1 > y) != (y2 > y):
            xi = x1 + (y - y1) * (x2 - x1) / (y2 - y1)
            if x < xi: inside = not inside
    return inside

def _esc(s): return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")

# ------------------------------------------------------------------ the data
def forms_of(A):
    if "forms" in A: return {k: v for k, v in A["forms"].items() if k != "practice"}
    return {"test": A["sections"]}

def extract(U, course):
    A = U["assessment"]
    def item(it):
        d = {"stem": it["stem"]}
        if it.get("fig"): d["fig"] = svg_of(it["fig"])
        if "parts" in it:
            d["parts"] = [{"label": p["label"], "stem": p["stem"], "answer": str(p["answer"]), "why": str(p.get("why", "")), "space": p.get("space", 0.6)} for p in it["parts"]]
        elif "choices" in it:
            d["choices"] = [str(c) for c in it["choices"]]; corr = it["correct"]
            d["correct"] = list(corr) if isinstance(corr, list) else [corr]; d["multi"] = isinstance(corr, list)
            d["answer"] = str(it["answer"]); d["why"] = str(it.get("why", "")); d["errors"] = {k: str(v) for k, v in (it.get("errors") or {}).items()}
        else:
            d["answer"] = str(it["answer"]); d["why"] = str(it.get("why", "")); d["space"] = it.get("space", 0.8)
        if it.get("transfer"): d["transfer"] = True
        return d
    forms = {}
    for fk, sections in forms_of(A).items():
        forms[fk] = [{"title": sec["title"], "benchmark": sec["benchmark"], "points": A["tracker"][sec["benchmark"]],
                      "items": [item(it) for it in sec["items"] if not it.get("heading") and not it.get("table_only")]} for sec in sections]
    return {"course": course, "unit": U["unit"], "title": U["title"], "total": A["total"], "tracker": A["tracker"], "tracker_order": A.get("tracker_order", list(A["tracker"])),
            "forms": forms, "notes": [SHOW_WORK + (("  " + A["pi_line"]) if A.get("pi_line") else "")], "two_day": TWO_DAY_LINE, "follow_through_student": FOLLOW_THROUGH,
            "follow_through_key": A.get("follow_through", ""), "transfer_flag": TRANSFER_FLAG}

def render(T): return HEADER + "window.TEACHER_TEST = " + json.dumps(T, ensure_ascii=False, indent=1) + ";\n"

# ------------------------------------------------------------------ the checks
def _sig(s):
    s = str(s).replace(",", "")
    if "." in s: return len(re.sub(r"\D", "", s).lstrip("0"))
    return len(s.strip("-").lstrip("0").rstrip("0"))

def _ev(expr):
    import sympy as sp
    env = {"F": lambda a, b=1: sp.Rational(a, b), "sqrt": sp.sqrt, "floor": sp.floor, "sig": _sig, "Integer": sp.Integer, "Rational": sp.Rational,
           "pi": sp.pi, "Abs": sp.Abs, "abs": sp.Abs, "N": sp.N, "nsimplify": sp.nsimplify, "Float": sp.Float,
           # the variables of an algebra check (A7 Unit 3's variable bases), declared positive exactly as the build kit's
           # gate declares them (kit/lib/lessonbuild.py _ev), so a check passes here exactly when it passes there
           **{s: sp.Symbol(s, positive=True) for s in "abcdkmnpqrstwxyz"}}
    return sp.sympify(eval(expr, {"__builtins__": {}}, env))

def run_check(chk, where, out):
    import sympy as sp
    k = chk[0]
    try:
        if k in ("eq", "val"):
            a, b = _ev(chk[1]), _ev(chk[2])
            if sp.simplify(a - b) != 0: out.append("%s: %s = %s but keyed %s = %s" % (where, chk[1], a, chk[2], b))
        elif k == "approx":
            a, b, tol = _ev(chk[1]), _ev(chk[2]), _ev(chk[3])
            if abs(float(a - b)) > float(tol): out.append("%s: %s ≈ %s, keyed %s, tol %s" % (where, chk[1], float(a), float(b), tol))
        elif k == "true":
            if not bool(_ev(chk[1])): out.append("%s: assertion false: %s" % (where, chk[1]))
        elif k == "many":
            for sub in chk[1:]: run_check(sub, where, out)
        else: out.append("%s: unknown check kind %s" % (where, k))
    except Exception as e:
        out.append("%s: check raised %r" % (where, e))

def check(U, T, out_path):
    bad = []
    have = open(out_path, encoding="utf-8").read() if os.path.exists(out_path) else ""
    if have != render(T): bad.append("test.js is not what unit.py gives now — run gen_test.py")
    A = U["assessment"]
    for fk, sections in forms_of(A).items():
        pts = 0
        for si, sec in enumerate(sections):
            spts = 0
            for ii, it in enumerate(sec["items"]):
                if it.get("heading") or it.get("table_only"): continue
                where = "form %s section %d item %d" % (fk, si + 1, ii + 1)
                if not it.get("stem"): bad.append(where + ": no stem")
                units = it.get("parts") or [it]
                for p in units:
                    if "check" not in p and not p.get("ack"): bad.append(where + ": a part with no check")
                    elif "check" in p: run_check(p["check"], where + ((" " + p.get("label", "")) if p is not it else ""), bad)
                    if p.get("answer") in (None, ""): bad.append(where + ": no answer")
                    spts += 1
                if "choices" in it:
                    corr = it["correct"] if isinstance(it["correct"], list) else [it["correct"]]
                    letters = re.findall(r"\b([A-H])\b", str(it["answer"]))
                    if sorted(LET[c] for c in corr) != sorted(letters): bad.append("%s: correct %s but answer says %r" % (where, corr, it["answer"]))
                    if any(c >= len(it["choices"]) for c in corr): bad.append(where + ": correct index out of range")
                if it.get("fig"):
                    try: svg_of(it["fig"])
                    except Exception as e: bad.append("%s: figure does not draw: %s" % (where, e))
            if spts != A["tracker"][sec["benchmark"]]: bad.append("form %s section %d: %d points but the tracker says %d" % (fk, si + 1, spts, A["tracker"][sec["benchmark"]]))
            pts += spts
        if pts != A["total"]: bad.append("form %s: %d points but total is %d" % (fk, pts, A["total"]))
    return bad

def main(unit_py, out="test.js", course=None):
    here = os.path.dirname(os.path.abspath(sys.argv[0]))
    unit_py = os.path.normpath(os.path.join(here, unit_py)); out = os.path.join(here, out)
    sys.path.insert(0, os.path.dirname(unit_py))
    U = runpy.run_path(unit_py)["U"]
    course = course or os.path.basename(os.path.dirname(os.path.dirname(os.path.dirname(unit_py)))).upper()
    T = extract(U, course)
    if "--check" in sys.argv:
        bad = check(U, T, out)
        n = sum(len(it.get("parts") or [it]) for f in T["forms"].values() for s in f for it in s["items"])
        if bad: print("\n".join(bad)); print("TEST CHECK FAILED (%d)" % len(bad)); sys.exit(1)
        print("test.js matches unit.py; forms %s; %d parts; every check re-passed under sympy; %d points a form" % (", ".join(T["forms"]), n, T["total"])); sys.exit(0)
    open(out, "w", encoding="utf-8").write(render(T)); print("wrote %s (forms %s)" % (os.path.basename(out), ", ".join(T["forms"])))
